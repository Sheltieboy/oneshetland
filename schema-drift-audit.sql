live as (
  select table_name::text t, column_name::text c
  from information_schema.columns where table_schema = 'public'
),
live_tables as (
  select table_name::text t from information_schema.tables
  where table_schema = 'public' and table_type = 'BASE TABLE'
),
live_fn as (
  select routine_name::text f from information_schema.routines
  where routine_schema = 'public'
)
select * from (
  -- a table the migrations create that the database does not have
  select 1 ord, 'TABLE MISSING FROM DB' issue, x.t as tbl, '' as col from (select distinct t from expected) x
  where not exists (select 1 from live_tables lt where lt.t = x.t)
  union all
  -- a column the migrations add that never landed  <-- the nudge_reminded_at class of bug
  select 2, 'COLUMN MISSING FROM DB', e.t, e.c from expected e
  where exists (select 1 from live_tables lt where lt.t = e.t)
    and not exists (select 1 from live l where l.t = e.t and l.c = e.c)
  union all
  -- a column in the database that no migration accounts for (hand-edit / lost migration)
  select 3, 'COLUMN NOT IN MIGRATIONS', l.t, l.c from live l
  where exists (select 1 from expected e where e.t = l.t)
    and not exists (select 1 from expected e where e.t = l.t and e.c = l.c)
  union all
  -- a public table nothing in the repo creates
  select 4, 'TABLE NOT IN MIGRATIONS', lt.t, '' from live_tables lt
  where not exists (select 1 from expected e where e.t = lt.t)
  union all
  -- an RPC the migrations define that is not live
  select 5, 'FUNCTION MISSING FROM DB', x.f, '' from (select distinct f from expected_fn) x
  where not exists (select 1 from live_fn lf where lf.f = x.f)
) d
order by ord, tbl, col;
